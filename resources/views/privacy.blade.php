            <p>El tratamiento de datos personales se fundamenta en:</p>
            <ul class="list-disc pl-5 space-y-1">
                <li>Consentimiento del interesado (Art. 6.1.a RGPD — Reglamento (UE) 2016/679).</li>
                <li>Cumplimiento de obligaciones legales (Art. 6.1.c RGPD) — Ley Orgánica 3/2020, Ley Orgánica 2/2006 de Educación, Decreto 114/2007 de Andalucía.</li>
                <li>Ejecución de un contrato o aplicación de medidas precontractuales (Art. 6.1.b RGPD) — relación académica con el centro.</li>
                <li>Interés legítimo (Art. 6.1.f RGPD) — mejora continua del servicio y seguridad del sistema.</li>
            </ul>

            <h2 class="text-lg font-semibold mt-4">3. Categorías de datos</h2>
            <p>Se recogen y tratan las siguientes categorías de datos personales:</p>
            <ul class="list-disc pl-5 space-y-1">
                <li><strong>Datos identificativos:</strong> nombre, apellidos, DNI/NIE, correo electrónico, teléfono.</li>
                <li><strong>Datos académicos:</strong> ciclo formativo, grupo, calificaciones, tutorías, anotaciones, proyectos.</li>
                <li><strong>Datos laborales (profesorado):</strong> departamento, asignaturas, horarios.</li>
                <li><strong>Datos de contacto de empresas:</strong> nombre, CIF, dirección, responsable, tutores laborales.</li>
                <li><strong>Datos de acceso:</strong> credenciales de autenticación, registro de actividad.</li>
            </ul>

            <h2 class="text-lg font-semibold mt-4">4. Destinatarios</h2>
            <ul class="list-disc pl-5 space-y-1">
                <li>No se cederán datos a terceros salvo obligación legal.</li>
                <li>Las empresas donde se realicen prácticas tendrán acceso limitado a los datos necesarios para la gestión de las mismas (nombre, ciclo, tutor).</li>
                <li>Las autoridades educativas competentes (Consejería de Educación de la Junta de Andalucía) podrán tener acceso a los datos en el ejercicio de sus funciones de inspección y control.</li>
                <li>El centro utiliza servicios de alojamiento y mantenimiento informático que pueden implicar el tratamiento de datos en el marco de un encargo de tratamiento (Art. 28 RGPD).</li>
            </ul>

            <h2 class="text-lg font-semibold mt-4">5. Plazo de conservación</h2>
            <p>Los datos se conservarán mientras dure la relación académica y los plazos legales aplicables:</p>
            <ul class="list-disc pl-5 space-y-1">
                <li><strong>Calificaciones:</strong> durante el curso académico y al menos 5 años después.</li>
                <li><strong>Convenios con empresas:</strong> durante la vigencia del convenio y 5 años después.</li>
                <li><strong>Registros de acceso:</strong> 3 años.</li>
                <li><strong>Datos de usuarios inactivos:</strong> 5 años tras el cese de la relación académica.</li>
            </ul>

            <h2 class="text-lg font-semibold mt-4">6. Derechos del interesado</h2>
            <p>Conforme al RGPD y a la Ley Orgánica 3/2018 (LOPDGDD), el interesado puede ejercer los siguientes derechos:</p>
            <ul class="list-disc pl-5 space-y-1">
                <li><strong>Derecho de acceso:</strong> obtener confirmificación de si se están tratando sus datos y conocer su contenido.</li>
                <li><strong>Derecho de rectificación:</strong> solicitar la modificación de datos inexactos o incompletos.</li>
                <li><strong>Derecho de supresión:</strong> solicitar la eliminación de sus datos cuando, entre otros, los datos ya no sean necesarios.</li>
                <li><strong>Derecho a la limitación del tratamiento:</strong> solicitar la limitación del tratamiento de sus datos.</li>
                <li><strong>Derecho a la portabilidad:</strong> recibir los datos en un formato estructurado y de uso común.</li>
                <li><strong>Derecho de oposición:</strong> oponerse al tratamiento de sus datos por motivos relacionados con su situación particular.</li>
            </ul>
            <p>Para ejercer estos derechos, puede dirigirse al Centro por escrito a la dirección indicada, adjuntando copia de un documento identificativo.</p>

            <h2 class="text-lg font-semibold mt-4">7. Medidas de seguridad</h2>
            <p>Se aplican medidas técnicas y organizativas adecuadas para proteger los datos personales conforme al RGPD, incluyendo:</p>
            <ul class="list-disc pl-5 space-y-1">
