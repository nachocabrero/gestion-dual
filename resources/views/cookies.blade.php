            <h2 class="text-lg font-semibold mt-4">1. ¿Qué son las cookies?</h2>
            <p>Las cookies son pequeños archivos de texto que se almacenan en tu dispositivo (ordenador, tablet o móvil) cuando visitas una página web. Se utilizan ampliamente para hacer que los sitios web funcionen de manera eficiente, así como para proporcionar información a los propietarios del sitio. Las cookies pueden ser "persistentes" o "de sesión", dependiendo de si se eliminan tras cerrar el navegador o si permanecen hasta que caduquen.</p>

