            </ul>

            <h3 class="text-base font-semibold mt-3">2.2. Cookies de preferencias</h3>
            <ul class="list-disc pl-5 space-y-1">
                <li><strong>cookie_consent</strong> — Almacena si has aceptado o rechazado las cookies no esenciales. Se almacena en sesión.</li>
